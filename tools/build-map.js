// Build-time pre-processing: geoBoundaries ADM2 GeoJSON -> small SVG paths (map-data.js).
// Usage: node tools/build-map.js <path-to-geoBoundaries-IDN-ADM2_simplified.geojson>
const fs = require("fs");
const path = require("path");
const src = process.argv[2];
if (!src) { console.error("Pass the GeoJSON path"); process.exit(1); }
const g = JSON.parse(fs.readFileSync(src, "utf8"));
const K = Math.cos(8.5 * Math.PI / 180);

const PANELS = {
  main: { lon: [114.40, 116.80], lat: [-8.02, -9.00], width: 1000,
    names: ["Badung","Bangli","Buleleng","Gianyar","Jembrana","Karang Asem","Klungkung","Kota Denpasar","Tabanan",
            "Lombok Barat","Lombok Tengah","Lombok Timur","Lombok Utara","Kota Mataram"] },
  close: { lon: [119.70, 120.00], lat: [-8.33, -8.62], width: 600, names: ["Manggarai Barat"] }
};

function simplify(ring, tol) { // closed ring: split at the farthest vertex, then Douglas-Peucker each half
  if (ring.length < 5) return ring;
  let far = 1, fd = 0;
  for (let i = 1; i < ring.length - 1; i++) { const d = Math.hypot(ring[i][0] - ring[0][0], ring[i][1] - ring[0][1]); if (d > fd) { fd = d; far = i; } }
  const a = dp(ring.slice(0, far + 1), tol), b = dp(ring.slice(far), tol);
  return a.concat(b.slice(1));
}
function dp(pts, tol) {
  if (pts.length < 3) return pts;
  const keep = new Uint8Array(pts.length); keep[0] = keep[pts.length - 1] = 1;
  const stack = [[0, pts.length - 1]];
  while (stack.length) {
    const [a, b] = stack.pop(); let max = 0, idx = -1;
    const [x1, y1] = pts[a], [x2, y2] = pts[b]; const dx = x2 - x1, dy = y2 - y1; const len = Math.hypot(dx, dy) || 1e-9;
    for (let i = a + 1; i < b; i++) { const d = Math.abs(dy * pts[i][0] - dx * pts[i][1] + x2 * y1 - y2 * x1) / len; if (d > max) { max = d; idx = i; } }
    if (max > tol && idx > 0) { keep[idx] = 1; stack.push([a, idx], [idx, b]); }
  }
  return pts.filter((_, i) => keep[i]);
}

const out = {};
for (const [key, P] of Object.entries(PANELS)) {
  const sx = P.width / ((P.lon[1] - P.lon[0]) * K);
  const height = Math.round((P.lat[0] - P.lat[1]) * sx);
  const proj = ([lon, lat]) => [(lon - P.lon[0]) * K * sx, (P.lat[0] - lat) * sx];
  const regions = [];
  for (const f of g.features) {
    if (!P.names.includes(f.properties.shapeName)) continue;
    const polys = f.geometry.type === "Polygon" ? [f.geometry.coordinates] : f.geometry.coordinates;
    let d = "", best = null, bestArea = 0;
    for (const poly of polys) {
      for (let r = 0; r < poly.length; r++) {
        let pts = poly[r].map(proj);
        const xs = pts.map(p => p[0]), ys = pts.map(p => p[1]);
        if (Math.max(...xs) < -20 || Math.min(...xs) > P.width + 20 || Math.max(...ys) < -20 || Math.min(...ys) > height + 20) continue;
        pts = simplify(pts, key === "main" ? 0.35 : 0.5);
        if (pts.length < 4) continue;
        let area = 0, cx = 0, cy = 0;
        for (let i = 0; i < pts.length - 1; i++) { const c = pts[i][0] * pts[i + 1][1] - pts[i + 1][0] * pts[i][1]; area += c; cx += (pts[i][0] + pts[i + 1][0]) * c; cy += (pts[i][1] + pts[i + 1][1]) * c; }
        if (Math.abs(area) < 4) continue; // drop specks
        if (r === 0 && Math.abs(area) > bestArea) { bestArea = Math.abs(area); best = [cx / (3 * area), cy / (3 * area)]; }
        d += "M" + pts.slice(0, -1).map(p => p[0].toFixed(1) + " " + p[1].toFixed(1)).join("L") + "Z";
      }
    }
    if (d) regions.push({ name: f.properties.shapeName, d, label: best && [+best[0].toFixed(0), +best[1].toFixed(0)] });
  }
  out[key] = { width: P.width, height, lon0: P.lon[0], lat0: P.lat[0], scale: +sx.toFixed(4), k: +K.toFixed(6), regions };
}
const js = "// Generated by tools/build-map.js from geoBoundaries gbOpen IDN ADM2 (simplified). Do not edit by hand.\n" +
  "// Projection: equirectangular, x scaled by cos(8.5deg).\nexport const MAP_DATA = " + JSON.stringify(out) + ";\n";
fs.writeFileSync(path.join(__dirname, "..", "map-data.js"), js);
console.log("map-data.js", js.length, "bytes;", Object.entries(out).map(([k, v]) => `${k}: ${v.regions.length} regions ${v.width}x${v.height}`).join(", "));
